#!/usr/bin/env python3
"""Packs the web page sources into the firmware header WebPages.h.

Run from any directory:  py -3 Software/Web_Pages/gen_web_pages.py
CI check (exit 1 when the header is stale):  python3 Software/Web_Pages/gen_web_pages.py --check

Line endings are normalised to LF first, so a checkout with CRLF gives the same header.

The gzip container is written here (fixed header, no file name, mtime 0, then raw deflate at level 9, CRC32 and
size), so only the deflate output depends on the installed zlib.

The HTML pages reference the stylesheet and the scripts as "/style.css" and so on. The generator appends
"?v=<hash of the asset>" to those references in the packed copy, so a browser that cached an asset for a day
fetches the new one as soon as the lamp serves a changed page. The server ignores the query string.
"""

import argparse
import hashlib
import os
import re
import struct
import sys
import zlib

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "Software_ver_2", "HAQuDA_Esp32", "sketches", "WebPages.h"))

# Served by HAQuDA_WebServer.cpp; the array names are WEB_<FILE>_<EXT>_GZ
SOURCES = ["index.html", "wifi_manager.html", "style.css", "app.js", "wifi.js"]
# Assets the pages load; the packed pages reference them with a content hash
VERSIONED_ASSETS = ["style.css", "app.js", "wifi.js"]

HEADER_COMMENT = (
    "// Generated by Software/Web_Pages/gen_web_pages.py from Software/Web_Pages/ - "
    "do not edit, edit the sources and re-run the script\n"
)
BYTES_PER_LINE = 16


def array_name(file_name):
    return "WEB_" + re.sub(r"[^A-Za-z0-9]", "_", file_name).upper() + "_GZ"


def read_source(file_name):
    with open(os.path.join(SCRIPT_DIR, file_name), "rb") as source:
        return source.read().replace(b"\r\n", b"\n")


def asset_hash(file_name):
    return hashlib.sha256(read_source(file_name)).hexdigest()[:8]


def served(file_name):
    """The bytes the lamp serves for a source: HTML pages get versioned asset references."""
    data = read_source(file_name)
    if not file_name.endswith(".html"):
        return data
    for asset in VERSIONED_ASSETS:
        pattern = rb"([\"'])/" + re.escape(asset.encode("ascii")) + rb"\1"
        replacement = rb"\1/" + asset.encode("ascii") + b"?v=" + asset_hash(asset).encode("ascii") + rb"\1"
        data = re.sub(pattern, replacement, data)
    return data


def gzip_bytes(data):
    # ID1 ID2, deflate, no flags, mtime 0, XFL 2 (best compression), OS 255 (unknown)
    header = bytes([0x1F, 0x8B, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0xFF])
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    body = compressor.compress(data) + compressor.flush()
    trailer = struct.pack("<II", zlib.crc32(data) & 0xFFFFFFFF, len(data) & 0xFFFFFFFF)
    return header + body + trailer


def pack(file_name):
    return gzip_bytes(served(file_name))


def carries_current_pages(current):
    """True when every array in the header unpacks to the pages the sources give.

    Only used to word the failure message: the pages are right and the compressed bytes differ.
    """
    found = {}
    for match in re.finditer(r"const uint8_t (\w+)\[\] PROGMEM = \{(.*?)\};", current.decode("ascii", "replace"), re.S):
        try:
            raw = bytes(int(token, 16) for token in re.findall(r"0x[0-9a-fA-F]{2}", match.group(2)))
            found[match.group(1)] = zlib.decompress(raw[10:-8], -15)
        except (zlib.error, ValueError):
            return False
    return found == {array_name(name): served(name) for name in SOURCES}


def render():
    # clang-format off/on keeps the commit hook from repacking the 16-bytes-per-line arrays
    lines = ["#pragma once\n", "\n", "#include <cstddef>\n", "#include <cstdint>\n", "\n", HEADER_COMMENT, "// clang-format off\n"]
    for file_name in SOURCES:
        packed = pack(file_name)
        name = array_name(file_name)
        lines.append("\n")
        lines.append("// {0}, {1} bytes gzipped\n".format(file_name, len(packed)))
        lines.append("const uint8_t {0}[] PROGMEM = {{\n".format(name))
        for start in range(0, len(packed), BYTES_PER_LINE):
            chunk = packed[start:start + BYTES_PER_LINE]
            lines.append("\t" + ", ".join("0x{0:02x}".format(b) for b in chunk) + ",\n")
        lines.append("};\n")
        lines.append("constexpr size_t {0}_LEN = sizeof({0});\n".format(name))
    lines.append("\n// clang-format on\n")
    return "".join(lines).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when WebPages.h differs from the sources")
    args = parser.parse_args()

    expected = render()
    if args.check:
        try:
            with open(OUTPUT, "rb") as handle:
                current = handle.read().replace(b"\r\n", b"\n")
        except FileNotFoundError:
            current = b""
        if current == expected:
            print("WebPages.h is up to date")
            return 0
        if carries_current_pages(current):
            # Same pages, other deflate bytes: a different zlib build (for example zlib-ng) compresses differently
            print("WebPages.h holds the current pages; its compressed bytes differ from this Python's zlib output (different zlib build)")
            return 0
        print("WebPages.h is stale: run 'py -3 Software/Web_Pages/gen_web_pages.py' and commit the result", file=sys.stderr)
        return 1

    with open(OUTPUT, "wb") as out:
        out.write(expected)
    print("wrote {0} ({1} bytes)".format(OUTPUT, len(expected)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
