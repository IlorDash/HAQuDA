#!/usr/bin/env python3
"""Packs the web page sources into the firmware header WebPages.h.

Run from any directory:  py -3 Software/Web_Pages/gen_web_pages.py
CI check (exit 1 when the header is stale):  python3 Software/Web_Pages/gen_web_pages.py --check

Line endings are normalised to LF first, so a checkout with CRLF gives the same header.

The gzip container is written here (fixed header, no file name, mtime 0, then raw deflate at level 9, CRC32 and
size), so only the deflate output depends on the installed zlib.

The HTML pages reference the stylesheet and the scripts as "/style.css" and so on. The generator appends
"?v=<hash of the asset>" to those references in the packed copy, so a browser that cached an asset for a day
fetches the new one as soon as the lamp serves a changed page. The server ignores the query string. The hash covers
the packed bytes, so an edit that only changes a comment does not change it.

The packed copy has the comments removed (JS // and /* */, CSS /* */, HTML <!-- -->) to keep the pages small; the
sources in Software/Web_Pages/ keep them. Nothing else is minified. A string, template literal, regular
expression or comment that does not end stops the script with exit code 1.
"""

import argparse
import hashlib
import os
import re
import struct
import sys
import zlib

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.normpath(os.path.join(SCRIPT_DIR, "..", "Software_ver_2", "HAQuDA_Esp32", "sketches", "WebPages.h"))

# Served by HAQuDA_WebServer.cpp; the array names are WEB_<FILE>_<EXT>_GZ
SOURCES = ["index.html", "wifi_manager.html", "style.css", "app.js", "wifi.js"]
# Assets the pages load; the packed pages reference them with a content hash
VERSIONED_ASSETS = ["style.css", "app.js", "wifi.js"]

HEADER_COMMENT = (
    "// Generated by Software/Web_Pages/gen_web_pages.py from Software/Web_Pages/ - "
    "do not edit, edit the sources and re-run the script\n"
)
BYTES_PER_LINE = 16


def array_name(file_name):
    return "WEB_" + re.sub(r"[^A-Za-z0-9]", "_", file_name).upper() + "_GZ"


def read_source(file_name):
    with open(os.path.join(SCRIPT_DIR, file_name), "rb") as source:
        return source.read().replace(b"\r\n", b"\n")


class StripError(Exception):
    pass


class Output:
    """Collects text and remembers the lines a removed comment touched, so they can be tidied at the end."""

    def __init__(self):
        self.parts = []
        self.line = 0
        self.touched = set()

    def append(self, text):
        self.parts.append(text)
        self.line += text.count("\n")

    def touch(self):
        self.touched.add(self.line)

    def result(self):
        lines = "".join(self.parts).split("\n")
        kept = []
        for index, line in enumerate(lines):
            if index in self.touched:
                line = line.rstrip()
                if not line:
                    continue
            kept.append(line)
        return "\n".join(kept)


JS_KEYWORDS_BEFORE_REGEX = {
    "return", "typeof", "instanceof", "in", "of", "new", "delete", "void", "throw", "case", "do", "else", "yield", "await",
}


def is_word_char(c):
    return c.isalnum() or c in "_$" or ord(c) > 127


def skip_string(text, start, name):
    quote = text[start]
    i = start + 1
    while i < len(text):
        c = text[i]
        if c == "\\":
            i += 2
        elif c == quote:
            return i + 1
        elif c == "\n":
            break
        else:
            i += 1
    raise StripError("{0}: unterminated string starting at line {1}".format(name, text.count("\n", 0, start) + 1))


def skip_regex(text, start, name):
    i = start + 1
    in_class = False
    while i < len(text):
        c = text[i]
        if c == "\\":
            i += 2
            continue
        if c == "\n":
            break
        if c == "[":
            in_class = True
        elif c == "]":
            in_class = False
        elif c == "/" and not in_class:
            return i + 1
        i += 1
    raise StripError("{0}: unterminated regular expression starting at line {1}".format(name, text.count("\n", 0, start) + 1))


def skip_template_part(text, start, name):
    """Returns (index after the part, True when a ${ substitution opens, False when the literal ends)."""
    i = start
    while i < len(text):
        c = text[i]
        if c == "\\":
            i += 2
        elif c == "`":
            return i + 1, False
        elif c == "$" and text[i + 1:i + 2] == "{":
            return i + 2, True
        else:
            i += 1
    raise StripError("{0}: unterminated template literal starting near line {1}".format(name, text.count("\n", 0, start) + 1))


def skip_comment(text, i, out, run_start, name):
    """Cuts the comment at text[i]; returns the index where copying resumes."""
    out.append(text[run_start:i])
    out.touch()
    if text[i + 1] == "/":
        end = text.find("\n", i)
        return len(text) if end < 0 else end
    end = text.find("*/", i + 2)
    if end < 0:
        raise StripError("{0}: unterminated comment starting at line {1}".format(name, text.count("\n", 0, i) + 1))
    if "\n" in text[i:end]:
        out.append("\n")
        out.touch()
    else:
        out.append(" ")
    return end + 2


def strip_js(text, name):
    out = Output()
    n = len(text)
    i = 0
    run_start = 0
    regex_allowed = True
    braces = []
    while i < n:
        c = text[i]
        if c == "/":
            following = text[i + 1:i + 2]
            if following in ("/", "*"):
                i = run_start = skip_comment(text, i, out, run_start, name)
            elif regex_allowed:
                i = skip_regex(text, i, name)
                regex_allowed = False
            else:
                i += 1
                regex_allowed = True
        elif c in "'\"":
            i = skip_string(text, i, name)
            regex_allowed = False
        elif c == "`" or (c == "}" and braces and braces[-1] == "template"):
            if c == "}":
                braces.pop()
            i, substitution = skip_template_part(text, i + 1, name)
            if substitution:
                braces.append("template")
            regex_allowed = substitution
        elif is_word_char(c):
            j = i
            while j < n and is_word_char(text[j]):
                j += 1
            regex_allowed = text[i:j] in JS_KEYWORDS_BEFORE_REGEX
            i = j
        elif c.isspace():
            i += 1
        else:
            if c == "{":
                braces.append("block")
            elif c == "}" and braces:
                braces.pop()
            regex_allowed = c not in ")]}"
            i += 1
    out.append(text[run_start:])
    return out.result()


def strip_css(text, name):
    out = Output()
    n = len(text)
    i = 0
    run_start = 0
    while i < n:
        c = text[i]
        if c == "/" and text[i + 1:i + 2] == "*":
            i = run_start = skip_comment(text, i, out, run_start, name)
        elif c in "'\"":
            i = skip_string(text, i, name)
        else:
            i += 1
    out.append(text[run_start:])
    return out.result()


RAW_ELEMENT = re.compile(r"<(script|style|pre|textarea)\b[^>]*>|<!--", re.I)


def strip_html(text, name):
    out = Output()
    i = 0
    while True:
        match = RAW_ELEMENT.search(text, i)
        if match is None:
            out.append(text[i:])
            break
        out.append(text[i:match.start()])
        if match.group(0) == "<!--":
            end = text.find("-->", match.end())
            if end < 0:
                raise StripError("{0}: unterminated HTML comment at line {1}".format(name, text.count("\n", 0, match.start()) + 1))
            out.touch()
            i = end + 3
            continue
        tag = match.group(1).lower()
        out.append(match.group(0))
        close = re.compile(r"</" + tag + r"\s*>", re.I).search(text, match.end())
        if close is None:
            raise StripError("{0}: <{1}> is not closed".format(name, tag))
        body = text[match.end():close.start()]
        if tag == "script" and "src=" not in match.group(0):
            body = strip_js(body, name + " <script>")
        elif tag == "style":
            body = strip_css(body, name + " <style>")
        out.append(body)
        out.append(close.group(0))
        i = close.end()
    return out.result()


def strip_comments(file_name, text):
    if file_name.endswith(".js"):
        return strip_js(text, file_name)
    if file_name.endswith(".css"):
        return strip_css(text, file_name)
    return strip_html(text, file_name)


def asset_hash(file_name):
    return hashlib.sha256(served(file_name)).hexdigest()[:8]


def served(file_name):
    """The bytes the lamp serves for a source: comments removed, HTML pages get versioned asset references."""
    data = strip_comments(file_name, read_source(file_name).decode("utf-8")).encode("utf-8")
    if not file_name.endswith(".html"):
        return data
    for asset in VERSIONED_ASSETS:
        pattern = rb"([\"'])/" + re.escape(asset.encode("ascii")) + rb"\1"
        replacement = rb"\1/" + asset.encode("ascii") + b"?v=" + asset_hash(asset).encode("ascii") + rb"\1"
        data = re.sub(pattern, replacement, data)
    return data


def gzip_bytes(data):
    # ID1 ID2, deflate, no flags, mtime 0, XFL 2 (best compression), OS 255 (unknown)
    header = bytes([0x1F, 0x8B, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, 0xFF])
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    body = compressor.compress(data) + compressor.flush()
    trailer = struct.pack("<II", zlib.crc32(data) & 0xFFFFFFFF, len(data) & 0xFFFFFFFF)
    return header + body + trailer


def pack(file_name):
    return gzip_bytes(served(file_name))


def carries_current_pages(current):
    """True when every array in the header unpacks to the pages the sources give.

    Only used to word the failure message: the pages are right and the compressed bytes differ.
    """
    found = {}
    for match in re.finditer(r"const uint8_t (\w+)\[\] PROGMEM = \{(.*?)\};", current.decode("ascii", "replace"), re.S):
        try:
            raw = bytes(int(token, 16) for token in re.findall(r"0x[0-9a-fA-F]{2}", match.group(2)))
            found[match.group(1)] = zlib.decompress(raw[10:-8], -15)
        except (zlib.error, ValueError):
            return False
    return found == {array_name(name): served(name) for name in SOURCES}


def render():
    # clang-format off/on keeps the commit hook from repacking the 16-bytes-per-line arrays
    lines = ["#pragma once\n", "\n", "#include <cstddef>\n", "#include <cstdint>\n", "\n", HEADER_COMMENT, "// clang-format off\n"]
    for file_name in SOURCES:
        packed = pack(file_name)
        name = array_name(file_name)
        lines.append("\n")
        lines.append("// {0}, {1} bytes gzipped\n".format(file_name, len(packed)))
        lines.append("const uint8_t {0}[] PROGMEM = {{\n".format(name))
        for start in range(0, len(packed), BYTES_PER_LINE):
            chunk = packed[start:start + BYTES_PER_LINE]
            lines.append("\t" + ", ".join("0x{0:02x}".format(b) for b in chunk) + ",\n")
        lines.append("};\n")
        lines.append("constexpr size_t {0}_LEN = sizeof({0});\n".format(name))
    lines.append("\n// clang-format on\n")
    return "".join(lines).encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when WebPages.h differs from the sources")
    args = parser.parse_args()

    try:
        expected = render()
    except StripError as error:
        print("cannot strip comments: {0}".format(error), file=sys.stderr)
        return 1
    if args.check:
        try:
            with open(OUTPUT, "rb") as handle:
                current = handle.read().replace(b"\r\n", b"\n")
        except FileNotFoundError:
            current = b""
        if current == expected:
            print("WebPages.h is up to date")
            return 0
        if carries_current_pages(current):
            # Same pages, other deflate bytes: a different zlib build (for example zlib-ng) compresses differently
            print("WebPages.h holds the current pages; its compressed bytes differ from this Python's zlib output (different zlib build)")
            return 0
        print("WebPages.h is stale: run 'py -3 Software/Web_Pages/gen_web_pages.py' and commit the result", file=sys.stderr)
        return 1

    with open(OUTPUT, "wb") as out:
        out.write(expected)
    print("wrote {0} ({1} bytes)".format(OUTPUT, len(expected)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
